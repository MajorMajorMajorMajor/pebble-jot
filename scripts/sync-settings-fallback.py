#!/usr/bin/env python3
"""Maintain an offline showConfiguration fallback equal to bundled config.html.

No note contents are embedded in the URL; only the static UI source is.
Run without arguments to synchronize, or --check in CI to verify the copy.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
START = "// JOT_EMBEDDED_SETTINGS_BEGIN (generated by scripts/sync-settings-fallback.py)"
END = "// JOT_EMBEDDED_SETTINGS_END"


def generate():
    html = (ROOT / "config.html").read_text(encoding="utf-8")
    return (
        START + "\n" +
        "var JOT_CONFIG_PAGE_HTML = " + json.dumps(html, ensure_ascii=False) + ";\n" +
        "// A missing/stale configPage locker entry must not silently disable Settings.\n" +
        "// This URL contains ONLY our static HTML, NEVER a user's notes.\n" +
        "Pebble.addEventListener('showConfiguration', function () {\n" +
        "  console.log('Jot: using self-contained Settings fallback');\n" +
        "  Pebble.openURL('data:text/html;charset=utf-8,' +\n" +
        "    encodeURIComponent(JOT_CONFIG_PAGE_HTML));\n" +
        "});\n" +
        END
    )


def main():
    path = ROOT / "src/js/pebble-js-app.js"
    text = path.read_text(encoding="utf-8")
    if text.count(START) != 1 or text.count(END) != 1:
        sys.exit("Missing or duplicated embedded settings markers")
    before, tail = text.split(START, 1)
    _, after = tail.split(END, 1)
    expected = before + generate() + after
    if sys.argv[1:] == ["--check"]:
        if text != expected:
            sys.exit("Embedded Settings page is stale: run python3 scripts/sync-settings-fallback.py")
        print("Embedded phone Settings fallback matches config.html")
    elif not sys.argv[1:]:
        if text != expected:
            path.write_text(expected, encoding="utf-8")
            print("Refreshed embedded phone Settings fallback")
    else:
        sys.exit("usage: python3 scripts/sync-settings-fallback.py [--check]")


if __name__ == "__main__":
    main()
