'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = p => fs.readFileSync(p,'utf8');
const touch = read('src/c/ui/touch.c');
const win = read('src/c/ui/window.c');
const grid = read('src/c/ui/key_grid.c');
const map = read('src/c/keyboard/flip_layout.c');
const num = read('src/c/keyboard/layout.c');
const book = read('src/c/keyboard/primary_face.c');
assert.match(touch,/s_touch_key == 13 &&\s*\(gesture_index == 17 \|\| gesture_index == 18\)/);
assert.match(touch,/keyboard_window_cycle_flip\(gesture_index == 17 \? 1 : -1\)/);
assert.match(touch,/s_touch_key == 13 && gesture_index == 0/);
assert.match(touch,/jot_editor_touch_save\(\)/);
assert.match(touch,/const int col = jot_flip_logical_column\(jot_flip_right\(mode\)/);
assert.match(touch,/jot_flip_bottom\(mode\) \? 0/);
assert.match(touch,/jot_flip_bottom\(flip\)/);
assert.match(touch,/s_header_touch_active = event->y >= editor_top/);
assert.match(touch,/if \(tap\) jot_reader_peek\(\)/);
assert.match(touch,/const bool at_right = s_stroke.start_x/);
assert.match(touch,/const bool at_left = s_stroke.start_x/);
assert.match(win,/persist_read_int\(JOT_FLIP_PERSIST_KEY\)/);
assert.match(win,/persist_write_int\(JOT_FLIP_PERSIST_KEY, \(int\)next\)/);
assert.match(win,/jot_flip_next\(self->flip_mode, direction\)/);
assert.match(win,/key_grid_set_right_hand\(self->grid, jot_flip_right\(next\)\)/);
assert.match(win,/layer_set_frame\(key_grid_get_layer\(self->grid\), frames.grid_frame\)/);
assert.match(win,/prv_attach_content_layer\(self\)/);
assert.match(win,/key_grid_create\(layout, dimensions.grid_frame, self->style,/);
assert.match(win,/key_grid_create\(get_layout\(next_id\),/);
assert.match(grid,/jot_flip_visual_column\(right_hand, \(int\)pos->col\)/);
assert.match(grid,/void key_grid_set_right_hand\(KeyGrid \*grid, bool right_hand\)/);
assert.doesNotMatch(touch,/keyboard_window_toggle_primary|keyboard_window_toggle_secondary/);
assert.doesNotMatch(map,/persist_write_data|jot_store/);
assert.match(num,/KEY_NUMBER_ZERO,\s*3,\s*1,\s*1,\s*2/);
assert.match(book,/'q', 'u', 'p', 'b', 'j', 'd', 'g', 'c'/);
console.log('Four-state flip routing, hit tests, persistence and input safety passed');
