// Protect the untouched tap/release recognizer while enabling hold-to-repeat.
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const s = fs.readFileSync('src/c/ui/touch.c', 'utf8');
const c = fs.readFileSync('src/c/ui/key_repeat.c', 'utf8');

assert.match(s, /#include "ui\/key_repeat\.h"/);
assert.match(s, /static AppTimer \*s_repeat_timer/);
assert.match(s, /app_timer_register\(delay_ms, prv_repeat_tick, NULL\)/);
assert.match(s, /s_stroke\.active &&|!s_stroke\.active/);
assert.match(s, /jot_key_repeat_due\(&s_repeat, now_ms\)/);
assert.match(s, /jot_key_repeat_begin\(&s_repeat,/);
assert.match(s, /jot_key_repeat_observe\(&s_repeat,/);
assert.match(s, /prv_stop_repeat\(\);\s*\/\/ Always cancel the repeat stroke/);
assert.match(s, /const bool repeated = jot_key_repeat_end\(&s_repeat\)/);
assert.match(s, /if \(repeated\) break;/);
assert.match(s, /s_mode != MODE_JOT/);
assert.match(s, /jot_list_is_open\(\) \|\| jot_reader_is_open\(\)/);
assert.match(s, /const int threshold2 = JOT_REPEAT_SWIPE_MIN_PX/);
assert.match(s, /if \(dx \* dx \+ dy \* dy < threshold2\) return JOT_REPEAT_NONE/);
assert.ok(s.includes('jot_input("' + String.fromCharCode(92) + 'b");'), 'repeat uses a real C backspace escape');
assert.match(s, /jot_delete_forward\(\)/);
assert.match(s, /jot_store_move_cursor\(move\)/);
assert.match(s, /prv_update_repeat\(event, now_ms\)/);
assert.match(c, /if \(state->fired\)/);
assert.match(c, /state->blocked = true/);
assert.match(c, /if \(gesture < 0 \|\| gesture > 8\)/);
assert.match(c, /key == 14 && numeric/);
assert.match(c, /key == 9 && !numeric/);
assert.match(s, /if \(s_touch_key == 13 && gesture_index == 0\)/);
assert.match(s, /jot_editor_touch_save\(\)/);
assert.match(s, /keyboard_window_toggle_number_face\(\)/);
assert.match(s, /s_mode == MODE_TRACE/);
console.log('Held-edit repeat: timers, cancellation and release routing verified');
