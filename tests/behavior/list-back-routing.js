'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const src = fs.readFileSync('src/c/jot/jot.c', 'utf8');
const focus = fs.readFileSync('src/c/jot/list_focus.c', 'utf8');
const start = src.indexOf('static void prv_list_back(');
const end = src.indexOf('static void prv_list_export(', start);
assert(start >= 0 && end > start, 'Back handler not found');
const handler = src.slice(start, end);
assert.match(handler, /touch_cancel_kinetic\(\)/);
assert.match(handler, /if \(s_confirm_delete\)/);
assert.match(handler, /if \(jot_list_back_should_scroll\(s_list_scroll_px\)\)/);
assert.match(handler, /s_list_scroll_px = 0/);
assert.match(handler, /s_selected_rank = jot_list_focus_initial\(0, jot_store_count\(\)\)/);
assert.match(handler, /s_list_focus_valid = true/);
assert.match(handler, /if \(prv_flush\(\)\) window_stack_pop_all\(true\)/);
assert.doesNotMatch(handler, /prv_restore_list_focus|prv_follow_list_focus|jot_list_focus_back/);
assert.match(focus, /return scroll_px > 0/);
console.log('Note list Back routing: true scroll offset, safe exit and modal precedence passed');
