const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = p => fs.readFileSync(p,'utf8');
const key = read('src/c/keyboard/key.c');
const layout = read('src/c/keyboard/layout.c');
const touch = read('src/c/ui/touch.c');
const window = read('src/c/ui/window.c');
const grid = read('src/c/ui/key_grid.c');
const button = read('src/c/ui/key_button.c');
const abc = read('src/c/keyboard/layout.h');
assert.match(abc,/LAYOUT_ENGLISH_123,/);
assert.match(layout,/english_123_keys\[\]/);
assert.match(layout,/\[LAYOUT_ENGLISH_123\]/);
for(const id of ['7','8','9','4','5','6','1','2','3']) {
  assert.match(key,new RegExp('KEY_NUMBER_'+id));
  assert.match(layout,new RegExp('KEY_NUMBER_'+id));
}
assert.match(layout,/KEY_NUMBER_ZERO,\s*3,\s*1,\s*1,\s*2/);
assert.match(layout,/KEY_NUMBER_SPACEBAR,\s*3,\s*3,\s*1,\s*1/);
assert.match(layout,/KEY_NUMBER_ABC,\s*1,\s*0,\s*1,\s*1/);
assert.match(window,/KeyGrid \*next = key_grid_create\(get_layout\(next_id\)/);
assert.match(window,/if \(!next\) return false/);
assert.match(window,/key_grid_destroy\(old\)/);
assert.match(grid,/grid->layout == get_layout\(LAYOUT_ENGLISH_123\)/);
// Zero uses the ordinary number-key cream fill and bevel, not gold Space styling.
assert.doesNotMatch(button,/button->key == get_key\(KEY_NUMBER_ZERO\)/);
assert.match(button,/label->key == get_key\(KEY_NUMBER_ABC\)/);
assert.match(touch,/s_touch_key == 12 && gesture_index == 0/);
assert.match(touch,/keyboard_window_toggle_number_face\(\)/);
const numericBranch = touch.indexOf('keyboard_window_number_face_active() &&');
const cursorBranch = touch.indexOf('!prv_jot_cursor_command(s_touch_key, gesture_index)', numericBranch);
assert.ok(numericBranch > 0 && cursorBranch > numericBranch,
  'number DOWN punctuation must run before ABC cursor shortcuts');
assert.match(touch,/jot_input\(jot_number_face_binding\(s_touch_key, gesture_index\)\)/);
assert.match(touch,/s_touch_key == 2 && gesture_index == 1/);
assert.match(touch,/s_touch_key == 8 && gesture_index == 5/);
assert.match(touch,/jot_store_move_cursor\(JOT_CURSOR_UP\)/);
assert.match(touch,/jot_store_move_cursor\(JOT_CURSOR_DOWN\)/);
assert.match(button,/FONT_KEY_GOTHIC_28_BOLD/);
assert.match(button,/prv_draw_number_legends\(ctx, button->key, bounds\)/);
assert.doesNotMatch(button,/prv_draw_number_pictogram|JotNumberPictogram/);
assert.doesNotMatch(button,/const int split = bounds.size.w \* 2 \/ 3/);
assert.match(grid,/KEY_NUMBER_ABC, KEY_ENGLISH_MENU, KEY_NUMBER_SPACEBAR/);
assert.match(touch,/jot_number_face_bottom_touch\(col\)/);
assert.match(touch,/s_touch_key == 14/);
assert.match(touch,/jot_input\(s_bindings\[9\]\[gesture_index\]\)/);
assert.match(touch,/s_touch_key < 14/);
assert.match(button,/FONT_KEY_GOTHIC_14_BOLD/);
assert.doesNotMatch(button,/GColorFromRGB\(170, 255, 255\)/);
assert.doesNotMatch(button,/numeric_digit|numeric_zero|numeric_space/);
assert.match(button,/GColorFromRGB\(0, 85, 170\)/);
assert.match(button,/prv_feedback_fill\(special, space, level, style\)/);
assert.match(key,/\[KEY_NUMBER_SPACEBAR\] = \{ \.labels = \{ \{0\} \} \}/);
assert.match(button,/jot_number_face_legend\(\(int\)index, d\)/);
const number = read('src/c/keyboard/number_face.c');
assert.doesNotMatch(number,/JOT_NUM_PICTO|jot_number_face_pictogram/);
assert.match(number,/text\[0\] > ' '/);
assert.match(touch,/jot_number_face_binding\(s_touch_key, gesture_index\)/);
assert.match(touch,/jot_editor_touch_save\(\)/);
assert.match(touch,/prv_jot_cursor_command\(s_touch_key, gesture_index\)/);
assert.match(touch,/prv_jot_forward_delete_command\(s_touch_key, gesture_index\)/);
console.log('123 layout geometry, display, routing and alphabet protections OK');
